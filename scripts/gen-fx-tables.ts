// Writes public/fx-tables.js: the firmware's level tables (vendor/fx/core/AudioEngine/ConstantValues/ampLogarythmicValues.h) as numbers, for the dB labels of the
// send and level knobs. test/fx.test.ts checks the file against the tables the wasm host exports, so a stale copy cannot pass.
// Usage: bun scripts/gen-fx-tables.ts
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const header = readFileSync(join(root, "vendor/fx/core/AudioEngine/ConstantValues/ampLogarythmicValues.h"), "utf8")

export function table(name: string): number[] {
  const m = header.match(new RegExp(`const float ${name}\\[AMP_LOG_VALUES\\] = \\{([^}]*)\\}`))
  if (!m) throw new Error(`no table ${name}`)
  const v = m[1].split(",").map((x) => Number(x.trim()))
  if (v.length !== 101 || v.some((x) => !Number.isFinite(x))) throw new Error(`table ${name}: ${v.length} values`)
  return v
}

/** limiterThresholdValues: the 101 steps of the limiter's Threshold (uint16). */
export function limiterTable(): number[] {
  const m = header.match(/const uint16_t limiterThresholdValues\[AMP_LOG_VALUES\] = \{([^}]*)\}/)
  if (!m) throw new Error("no table limiterThresholdValues")
  const v = m[1].split(",").map((x) => Number(x.trim()))
  if (v.length !== 101 || v.some((x) => !Number.isFinite(x))) throw new Error(`table limiterThresholdValues: ${v.length} values`)
  return v
}

if (import.meta.main) {
  const out = `// Generated by scripts/gen-fx-tables.ts from the firmware's ampLogarythmicValues.h (vendor/fx). Do not edit.
// sends: sendsAmpLogValues, the gain of a synth part's Delay send and Reverb send. levels: mixAmpLogValues, the gain of the Delay and Reverb levels of the Mixer page.
export const sends = ${JSON.stringify(table("sendsAmpLogValues"))}
export const levels = ${JSON.stringify(table("mixAmpLogValues"))}
// limiter: limiterThresholdValues, the 101 steps of the master limiter's Threshold (int16 units, 32767 = 0 dB).
export const limiter = ${JSON.stringify(limiterTable())}
`
  writeFileSync(join(root, "public/fx-tables.js"), out)
  console.log("public/fx-tables.js written")
}
